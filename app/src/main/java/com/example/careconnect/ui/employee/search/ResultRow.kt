@Composable
fun ResultRowPreview() {
    CareConnectTheme(darkTheme = false) {
        ResultRow(
            icon = Icons.Default.Person,
            title = MockData.patient.name,
            subtitle = MockData.patient.fullAddress,
            onClick = {}
        )
    }
}
